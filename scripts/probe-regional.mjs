/**
 * **What each Regional OTT row actually holds, in the region it is read in.**
 *
 * `tmdb-verified.json` records the counts for the regions a service was *verified* in, and its
 * counts are measured once per service per region list — 1,206 rows. This probe measures the
 * smaller set that matters to the card instead: **every row the Regional OTT cards publish**,
 * asked with the region that row's own query carries (so `ROW_REGION`'s overrides are honoured)
 * and the same monetisation and vote floor the live catalog uses.
 *
 * The answer is written to `scripts/regional-counts.json`, keyed `<providerId>@<REGION>`, and
 * `collections.mjs` reads it to keep a row off the card when the row cannot fill a page. The
 * counts move with TMDB, so re-run this and the card follows:
 *
 *   node scripts/probe-regional.mjs
 *
 * A count of 0 means "TMDB answered nothing for this provider in this region" — an empty row,
 * which is what the customer reported more than once (BritBox, Exxen, IROKOTV).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { regionalRoster } from "./collections.mjs";

const key = JSON.parse(readFileSync(new URL("../addon/settings.json", import.meta.url), "utf8"))
  .providers?.tmdb?.key || "";
if (!key) throw new Error("no TMDB key in addon/settings.json");

const OUT = new URL("./regional-counts.json", import.meta.url);
const FALLBACK_REGION = "US";

/** How many titles TMDB says a row answers — the same query shape `addon/catalogs.mjs` sends. */
async function count(media, providerId, region) {
  const u = new URL(`https://api.themoviedb.org/3/discover/${media}`);
  u.searchParams.set("api_key", key);
  u.searchParams.set("watch_region", region);
  u.searchParams.set("with_watch_providers", String(providerId));
  u.searchParams.set("with_watch_monetization_types", "flatrate");
  u.searchParams.set("sort_by", "popularity.desc");
  u.searchParams.set("vote_count.gte", "10");
  for (let attempt = 0; attempt < 3; attempt += 1) {
    const res = await fetch(u);
    if (res.ok) {
      const body = await res.json();
      return Number(body.total_results || 0);
    }
    if (res.status === 429) await new Promise((r) => setTimeout(r, 1500 * (attempt + 1)));
    else throw new Error(`${res.status} for ${media} ${providerId} in ${region}`);
  }
  throw new Error(`rate-limited on ${media} ${providerId} in ${region}`);
}

/**
 * Every row the cards can draw — **as the roster, not as the card.** Reading the card would
 * make the probe follow the cull: a culled row would stop being measured, the next build would
 * find no count for it, and the row would come back. See `regionalRoster`.
 */
const rows = [];
for (const media of ["movie", "tv"]) {
  for (const entry of regionalRoster(media)) {
    rows.push({
      media,
      name: entry.name,
      providerId: Number(entry.id),
      region: String(entry.region || FALLBACK_REGION).toUpperCase(),
    });
  }
}
// One probe per (provider, region, media): a row can be listed under two names (the Top 10 twin
// is not in this list, but the same provider can arrive from a continent row as well).
const unique = new Map(rows.map((r) => [`${r.providerId}@${r.region}:${r.media}`, r]));
console.log(`probing ${unique.size} rows (${rows.length} published rows)`);

const out = {};
const queue = [...unique.values()];
const workers = Array.from({ length: 8 }, async () => {
  for (;;) {
    const row = queue.shift();
    if (!row) return;
    const slot = `${row.providerId}@${row.region}`;
    const held = (out[slot] = out[slot] || { name: row.name, region: row.region, movie: 0, tv: 0 });
    try {
      held[row.media] = await count(row.media, row.providerId, row.region);
    } catch (err) {
      held[row.media] = -1;
      console.log(`  ! ${row.name} (${row.providerId} ${row.region}) ${row.media}: ${err.message}`);
    }
    console.log(`  ${row.name.padEnd(22)} ${row.region} ${row.media.padEnd(6)} ${held[row.media]}`);
  }
});
await Promise.all(workers);

const sorted = Object.fromEntries(
  Object.entries(out).sort(([a], [b]) => a.localeCompare(b)),
);
writeFileSync(OUT, JSON.stringify({
  note: "Generated by scripts/probe-regional.mjs against the live TMDB API. Read by collections.mjs.",
  measuredAt: new Date().toISOString().slice(0, 10),
  counts: sorted,
}, null, 2) + "\n");

const thin = Object.entries(sorted)
  .flatMap(([slot, c]) => [["movie", c.movie], ["tv", c.tv]].map(([t, n]) => ({ slot, name: c.name, t, n })))
  .filter((r) => r.n >= 0 && r.n < 25)
  .sort((a, b) => a.n - b.n);
console.log(`\nrows under 25 titles (${thin.length}):`);
for (const r of thin) console.log(`  ${String(r.n).padStart(5)}  ${r.t.padEnd(6)} ${r.name}  ${r.slot}`);
console.log(`\nwritten ${OUT.pathname}`);
